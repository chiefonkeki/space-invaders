/**
 * Draws a pixel grid matrix onto a 2D canvas context with neon styling
 */
export function drawPixelMatrix(
  ctx: CanvasRenderingContext2D,
  matrix: number[][],
  x: number,
  y: number,
  width: number,
  height: number,
  color: string,
  glow: boolean = true
) {
  const rows = matrix.length;
  const cols = matrix[0].length;
  const pixelW = width / cols;
  const pixelH = height / rows;

  ctx.save();
  ctx.fillStyle = color;
  if (glow) {
    ctx.shadowColor = color;
    ctx.shadowBlur = 6;
  }

  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      if (matrix[r][c] === 1) {
        ctx.fillRect(
          Math.floor(x + c * pixelW),
          Math.floor(y + r * pixelH),
          Math.ceil(pixelW),
          Math.ceil(pixelH)
        );
      }
    }
  }

  ctx.restore();
}
